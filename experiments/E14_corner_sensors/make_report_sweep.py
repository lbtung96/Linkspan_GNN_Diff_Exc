    for fam, lab in FAMILIES.items():
        add(f"## {lab.capitalize()}\n")
        add("| n | measured nodes | % of nodes | B1 | T1 | B2 | T2 | mean | freq. error (Hz) |")
        add("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
        for k in lv[fam]:
            s = stat(data[fam], f"n{k}")
