"""Assemble REPORT_SWEEP.md and the sensor-sweep figures from E14 stage 3.

Generated, never hand-edited. Reads `stage3_outer_*` and `stage3_all_*` (and
`raw_stage3_*` for the layouts); every number in the report is computed here.

Target: "about 0.8 MAC" is read as the mean over the four modes, pooled over all
held-out structures, with `last_model.pt` (the repo's test convention).
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(REPO))

MODES = ("B1", "T1", "B2", "T2")
NGS = (2, 3, 4, 5)
TARGET = 0.8
FAMILIES = {"outer": "outer girders only", "all": "every girder"}

# validated reference palette (categorical slots 1-4, light mode) + text/neutral tokens
C_MODE = {"B1": "#2a78d6", "T1": "#eb6834", "B2": "#1baf7a", "T2": "#eda100"}
C_FAM = {"outer": "#eb6834", "all": "#2a78d6"}
C_MEASURED, C_BAR = "#eb6834", "#2a78d6"
INK, INK_2, MUTED, GRID = "#0b0b0b", "#52514e", "#8a8984", "#e4e3df"
NG_MARK = {2: "o", 3: "s", 4: "^", 5: "D"}


def read(tag: str) -> list[dict]:
    with open(HERE / f"{tag}_per_sample.csv", newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k, v in r.items():
            try:
                r[k] = float(v)
            except ValueError:
                pass
    return rows


def levels_of(rows: list[dict]) -> list[int]:
    return sorted({int(r["variant"][1:]) for r in rows if r["variant"].startswith("n")})


def stat(rows: list[dict], variant: str, ck: str = "last", ng: int | None = None) -> dict:
    sel = [r for r in rows if r["variant"] == variant and r["checkpoint"] == ck
           and (ng is None or r["Ng"] == ng)]
    mac = np.array([[r[f"mac_{m}"] for m in MODES] for r in sel])
    ferr = np.array([[r[f"ferr_{m}"] for m in MODES] for r in sel])
    ns = np.array([r["n_sensors"] for r in sel])
    frac = np.array([r["n_sensors"] / r["n_nodes"] for r in sel])
    return {"mac": mac.mean(0), "mean": mac.mean(), "ferr": ferr.mean(), "n": len(sel),
            "sensors": ns.mean(), "pct": 100 * frac.mean(), "mac_all": mac,
            "sens_min": ns.min(), "sens_max": ns.max()}


def first_reach(rows, levels, ng=None) -> str:
    for lv in levels:
        s = stat(rows, f"n{lv}", ng=ng)
        if s["mean"] >= TARGET:
            return (f"n = {lv} ({s['sensors']:.0f} nodes, {s['pct']:.0f}%)" if ng is not None
                    else f"n = {lv} ({s['sensors']:.1f} nodes on average, {s['pct']:.0f}%)")
    return "not reached"


PREFIX = "stage3"


