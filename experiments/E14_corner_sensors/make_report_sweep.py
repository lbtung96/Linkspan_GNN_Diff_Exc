def pick_representatives(rows: list[dict]) -> dict[int, str]:
    """Per Ng, the structure with the median node count (fixed across all cases)."""
    reps = {}
    for g in NGS:
        cand = sorted({(r["n_nodes"], r["sample"]) for r in rows if r["Ng"] == g})
        reps[g] = cand[len(cand) // 2][1]
    return reps


def _style(plt) -> None:
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": INK_2, "axes.labelcolor": INK,
                         "xtick.color": INK_2, "ytick.color": INK_2})


def _draw_layout(ax, raw, sensors, title) -> None:
    xy, ei = raw["coords"], raw["edge_index"]
    for a, b in ei.T[ei[0] < ei[1]]:
        ax.plot(xy[[a, b], 0], xy[[a, b], 1], color=GRID, lw=0.8, zorder=1)
    mask = np.zeros(len(xy), bool)
    mask[sensors] = True
    ax.scatter(xy[~mask, 0], xy[~mask, 1], s=14, facecolors="white", edgecolors=MUTED,
               linewidths=0.7, zorder=2)
    ax.scatter(xy[mask, 0], xy[mask, 1], s=60, color=C_MEASURED, edgecolors=INK,
               linewidths=0.8, zorder=3)
    ax.set_title(title, fontsize=9, color=INK, loc="left")
    ax.set_aspect("equal")
    ax.set_xticks([])
    ax.set_yticks([])
    for side in ax.spines.values():
        side.set_visible(False)
    y0 = xy[:, 1].min() - 0.12 * (np.ptp(xy[:, 1]) + 1)
    ax.text(xy[:, 0].min(), y0, "hinge", fontsize=8, color=INK_2, ha="left", va="top")
    ax.text(xy[:, 0].max(), y0, "front beam", fontsize=8, color=INK_2, ha="right", va="top")


def case_figure(fam: str, k: int, rows: list[dict], reps: dict) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    _style(plt)
    raw = {g: np.load(HERE / f"raw_{PREFIX}_{fam}" / f"{reps[g]}.npz") for g in NGS}
    s_all = stat(rows, f"n{k}")
    full = stat(rows, "full")
    fig = plt.figure(figsize=(15, 7.2))
    gs = fig.add_gridspec(2, 4, height_ratios=[1.0, 1.15], hspace=0.35, wspace=0.08)
    for i, g in enumerate(NGS):
        ax = fig.add_subplot(gs[0, i])
        sens = raw[g][f"sensors_n{k}"]
        n_nodes = len(raw[g]["coords"])
        _draw_layout(ax, raw[g], sens,
                     f"Ng = {g}: {len(sens)} of {n_nodes} nodes measured")
    ax = fig.add_subplot(gs[1, :])
    pos = np.arange(4)
    bars = ax.bar(pos, s_all["mac"], width=0.55, color=C_BAR, zorder=2)
    for b, v in zip(bars, s_all["mac"]):
        inside = v > 0.15                     # inside the bar, clear of the full-graph line
        ax.text(b.get_x() + b.get_width() / 2, v - 0.02 if inside else v + 0.015, f"{v:.2f}",
                ha="center", va="top" if inside else "bottom", fontsize=11,
                color="white" if inside else INK, fontweight="bold", zorder=5)
    for j in range(4):
        ax.plot([j - 0.33, j + 0.33], [full["mac"][j]] * 2, color=INK, lw=1.4, ls=(0, (4, 2)),
                zorder=3)
    for g in NGS:
        sg = stat(rows, f"n{k}", ng=g)
        ax.scatter(pos + 0.36, sg["mac"], marker=NG_MARK[g], s=34, facecolors="white",
                   edgecolors=INK_2, linewidths=1.1, zorder=4)
    ax.axhline(TARGET, color=MUTED, lw=1, zorder=1)
    ax.text(-0.57, TARGET + 0.01, f"target {TARGET}", fontsize=8, color=INK_2, va="bottom", ha="left")
    ax.set_xticks(pos, MODES)
    ax.set_xlim(-0.6, 3.75)
    ax.set_ylim(0, 1.08)
    ax.set_ylabel("MAC vs FE target")
    ax.grid(axis="y", color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    handles = [Line2D([], [], marker="s", ls="", color=C_BAR, markersize=10,
                      label=f"mean over all {s_all['n']} structures"),
               Line2D([], [], color=INK, lw=1.4, ls=(0, (4, 2)), label="full graph (every node measured)")]
    handles += [Line2D([], [], marker=NG_MARK[g], ls="", markerfacecolor="white",
                       markeredgecolor=INK_2, label=f"Ng = {g}") for g in NGS]
    handles += [Line2D([], [], marker="o", ls="", color=C_MEASURED, markeredgecolor=INK,
                       label="measured node (layouts)"),
                Line2D([], [], marker="o", ls="", markerfacecolor="white",
                       markeredgecolor=MUTED, label="not measured: filled by propagation")]
    ax.legend(handles=handles, frameon=False, ncol=4, fontsize=8.5, loc="upper center",
              bbox_to_anchor=(0.5, -0.1))
    cnt = (f"{2 * k} measured nodes" if fam == "outer"
           else f"Ng x {k} measured nodes ({s_all['sensors']:.1f} on average)")
    fig.suptitle(f"{FAMILIES[fam].capitalize()}, n = {k} station{'s' if k > 1 else ''} per "
                 f"girder: {cnt}, {s_all['pct']:.0f}% of the deck - mean MAC "
                 f"{s_all['mean']:.2f}", fontsize=12, color=INK, x=0.02, ha="left")
    fig.savefig(HERE / f"fig_sweep_{fam}_n{k:02d}.png", dpi=140, bbox_inches="tight")
    plt.close(fig)


def summary_figure(data, lv) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    _style(plt)
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.4), sharey=True)
    for ax, (fam, lab) in zip(axes, FAMILIES.items()):
        S = [stat(data[fam], f"n{k}") for k in lv[fam]]
        x = [s["pct"] for s in S]
        ends = []
        for j, m in enumerate(MODES):
            y = [s["mac"][j] for s in S]
            ax.plot(x, y, color=C_MODE[m], lw=2, marker="o", markersize=5, zorder=3)
            ends.append([y[-1], m, "normal", C_MODE[m]])
        ym = [s["mean"] for s in S]
        ax.plot(x, ym, color=INK, lw=2.6, marker="o", markersize=6, zorder=4)
        ends.append([ym[-1], "mean", "bold", INK])
        ends.sort(key=lambda e: e[0])
        for i in range(1, len(ends)):                      # keep end labels 0.035 apart
            ends[i][0] = max(ends[i][0], ends[i - 1][0] + 0.035)
        for y_lab, m, wt, col in ends:
            ax.plot([x[-1] + 0.6, x[-1] + 1.6], [y_lab, y_lab], color=col, lw=2.4,
                    solid_capstyle="round", clip_on=False)
            ax.text(x[-1] + 1.9, y_lab, m, color=INK, fontsize=9, va="center", fontweight=wt)
        ax.text(0.5, 0.075, "measured nodes:", fontsize=7.5, color=INK_2)
        for s, xx in zip(S, x):
            lab_n = f"{s['sensors']:.0f}" if fam == "outer" else f"{s['sensors']:.1f}"
            ax.text(xx, 0.03, lab_n, ha="center", fontsize=7.5, color=INK_2)
        full = stat(data[fam], "full")["mean"]
        ax.axhline(TARGET, color=INK_2, lw=1, ls=(0, (5, 3)), zorder=1)
        ax.axhline(full, color=MUTED, lw=1, zorder=1)
        ax.text(0.5, TARGET + 0.01, f"target {TARGET}", fontsize=8, color=INK_2)
        ax.text(0.5, full + 0.01, f"full graph {full:.2f}", fontsize=8, color=INK_2)
        ax.set_xlim(0, max(x) + 6)
        ax.set_ylim(0, 1.0)
        ax.set_xlabel("measured nodes, % of the deck" + ("" if fam == "outer" else
                      "  (counts along the bottom: mean over girder counts)"))
        ax.set_title(lab.capitalize(), fontsize=11, color=INK, loc="left")
        ax.grid(color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_ylabel("MAC vs FE target (mean over held-out structures)")
    from matplotlib.lines import Line2D
    axes[0].legend(handles=[Line2D([], [], color=C_MODE[m], lw=2, marker="o", markersize=5,
                                   label=m) for m in MODES]
                   + [Line2D([], [], color=INK, lw=2.6, marker="o", markersize=6,
                             label="mean of the four")],
                   frameon=False, fontsize=9, loc="lower right", bbox_to_anchor=(1.0, 0.1))
    fig.suptitle("More measured nodes, higher MAC - N = 10 000 network, "
                 f"{stat(data['all'], 'full')['n']} held-out structures", fontsize=12,
                 color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(HERE / "fig_sweep_summary.png", dpi=160)
    plt.close(fig)


def by_ng_figure(data, lv) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    _style(plt)
    fig, axes = plt.subplots(1, 4, figsize=(16, 4.6), sharey=True)
    for ax, g in zip(axes, NGS):
        for fam in ("all", "outer"):
            S = [stat(data[fam], f"n{k}", ng=g) for k in lv[fam]]
            x = [s["sensors"] for s in S]
            ax.plot(x, [s["mean"] for s in S], color=C_FAM[fam], lw=2.2, marker="o",
                    markersize=5, label=FAMILIES[fam], zorder=3)
        ax.axhline(TARGET, color=INK_2, lw=1, ls=(0, (5, 3)))
        ax.axhline(stat(data["all"], "full", ng=g)["mean"], color=MUTED, lw=1)
        same = " - families identical" if g == 2 else ""
        ax.set_title(f"Ng = {g}  (full graph {stat(data['all'], 'full', ng=g)['mean']:.2f}){same}",
                     fontsize=10, color=INK, loc="left")
        ax.set_xlabel("measured nodes")
        ax.set_ylim(0, 1.0)
        ax.grid(color=GRID, lw=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
    axes[0].set_ylabel("mean MAC over the four modes")
    axes[0].legend(frameon=False, fontsize=9, loc="lower right")
    fig.suptitle("By girder count: dashed = 0.8 target, grey = full graph", fontsize=11,
                 color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(HERE / "fig_sweep_by_ng.png", dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    raise SystemExit(main())
