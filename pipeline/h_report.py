DECISION = ((0.8, "the approach generalises when trained correctly"),
            (0.5, "partly"),
            (-1.0, "does not"))


def jload(name: str) -> dict:
    p = R / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def f3(x) -> str:
    return "" if x in (None, "") else f"{float(x):.3f}"


def ci(row: dict, col: str) -> str:
    return f"{float(row[col]):.3f} [{float(row[col + '_lo']):.3f}, {float(row[col + '_hi']):.3f}]"


def sgn(x: float) -> str:
    return f"{x:+.3f}"


def table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def verdict_band(v: float) -> str:
    for thr, txt in DECISION:
        if v >= thr:
            return txt
    return DECISION[-1][1]


def run_info(name: str) -> dict:
    for root in (C.RUNS, H.EC_RUNS):
        p = root / name / "run_summary.json"
        if p.exists():
            d = json.loads(p.read_text(encoding="utf-8"))
            d["_root"] = "paper runs/" if root == C.RUNS else "runs/ec/"
            h = list(csv.DictReader((root / name / "training_history.csv").open(encoding="utf-8")))
            d["_hist"] = h
            return d
    return {}


def ledger() -> list[dict]:
    p = C.REPO / "results" / "RUN_LEDGER.jsonl"
    out = []
    for line in p.read_text(encoding="utf-8").splitlines():
        try:
            r = json.loads(line)
        except json.JSONDecodeError:
            continue
        if "pipeline/h_" in r.get("stage", "").replace("\\", "/"):
            out.append(r)
    return out


