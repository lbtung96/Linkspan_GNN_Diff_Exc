        rows = []
        for s in C.LOOCV:
            for m in MODES:
                rows.append([s, m] + [f3(next(float(r["mac_ssi"]) for r in zs if r["arm"] == n and r["structure"] == s
                                              and r["mode"] == m)) for n in nets_r])
        L += table(["bridge", "mode"] + [f"`{n}`" for n in nets_r], rows)
