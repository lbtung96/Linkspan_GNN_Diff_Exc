"""T5 (EC-15) - generate a fresh, untouched synthetic test set from the paper's distribution.

    python tools/run_stage.py Final_results_for_paper/EC_comments/pipeline/c_gen_fresh_test.py --set fresh_test
    python tools/run_stage.py Final_results_for_paper/EC_comments/pipeline/c_gen_fresh_test.py --set fresh_test_paperexc

500 structures, 125 per girder count (Ng = 2..5), broadband arm (all 15 FE modes, 1.5-20 Hz
zero-phase bandpass), generated by the production generator with exactly the paper's in-memory
patches (s0_generate_population.install_patches: Ng >= 3 spacing up to 3000 mm, selected-mode
MAC gate 0.85).  Nothing on disk is edited; two more module globals are replaced:

  generate_population_dataset_modes4.SEED            20260507 -> PARAM_SEED (20261123)
      drives the parameter draws: SeedSequence(SEED).spawn(4), one stream per Ng.
  simulate_uniform_inertial_u3_white_noise.SEED      12345 -> EXC_SEED
      drives the excitation: simulate_white_noise_from_modal_model calls
      np.random.default_rng(SEED) afresh for EVERY structure, so every paper structure
      (train, validation and test) was excited by the same white-noise realisation.

Two sets, the same 500 structures (the excitation is drawn after acceptance, so it cannot
change which structures are accepted - checked by c_fresh_checks.py):

  fresh_test            PARAM_SEED 20261123, EXC_SEED 20261124  - the EC-15 test set
  fresh_test_paperexc   PARAM_SEED 20261123, EXC_SEED 12345     - control: new structures,
                                                                  the paper's excitation

Safety (CLAUDE.md hard rules 4-5): Agg backend before the generator is imported, an empty
non-TTY stdin before main(), the two protected lines of the generator are never touched (the
patches go to the imported module), and clean_output_directory is replaced by a guard that
refuses any path outside EC_comments/data/T5/ (main(bandpass=True) does not call it anyway;
it only empties OUT_DIR/samples_phase2_bandpass, which is inside our own folder).
"""

from __future__ import annotations

import os

for _v in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"):
    os.environ.setdefault(_v, "2")

import argparse  # noqa: E402
import io  # noqa: E402
import json  # noqa: E402
import platform  # noqa: E402
import sys  # noqa: E402
import time  # noqa: E402
from datetime import datetime, timezone  # noqa: E402
from pathlib import Path  # noqa: E402

import matplotlib  # noqa: E402

matplotlib.use("Agg")      # before anything imports pyplot (the generator does)

import numpy as np  # noqa: E402

import ec_common as E  # noqa: E402  (puts REPO and the paper pipeline on sys.path)

C = E.C
import s0_generate_population as S0  # noqa: E402  (imports the generator; patches nothing on import)
import simulate_uniform_inertial_u3_white_noise as SIM  # noqa: E402

gen = S0.gen
T5_DATA = E.EC_DATA / "T5"
PARAM_SEED = 20261123
EXC_SEED_NEW = 20261124
PAPER_EXC_SEED = 12345
SETS = {"fresh_test": EXC_SEED_NEW, "fresh_test_paperexc": PAPER_EXC_SEED}
N_TOTAL = 500


def guarded_clean(out_dir: Path) -> None:
    out_dir = Path(out_dir).resolve()
    if T5_DATA.resolve() not in out_dir.parents:
        raise RuntimeError(f"refusing to clean {out_dir}: not under {T5_DATA}")
    S0_clean(out_dir)


S0_clean = gen.clean_output_directory


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--set", choices=sorted(SETS), required=True)
    ap.add_argument("--n-total", type=int, default=N_TOTAL)
    args = ap.parse_args()

    out_root = (T5_DATA / args.set).resolve()
    if "population_dataset_modes4" in str(out_root) or T5_DATA.resolve() not in out_root.parents:
        raise RuntimeError(f"bad output root {out_root}")
    if (out_root / "samples_phase2_bandpass").exists() and any((out_root / "samples_phase2_bandpass").iterdir()):
        raise RuntimeError(f"{out_root} already holds samples; delete it by hand to regenerate")
    # the paper's values, before we change them
    if gen.SEED != C.GENERATOR_SEED or SIM.SEED != PAPER_EXC_SEED:
        raise RuntimeError(f"unexpected seeds gen.SEED={gen.SEED} SIM.SEED={SIM.SEED}")
    # the simulator the generator calls reads SEED from the simulator module at call time
    if gen.simulate_white_noise_from_modal_model.__globals__ is not SIM.__dict__:
        raise RuntimeError("generator's simulate function does not live in the simulator module")
    out_root.mkdir(parents=True, exist_ok=True)

    patches = S0.install_patches(out_root, args.n_total)          # the paper's own patches, unchanged
    gen.SEED = PARAM_SEED
    SIM.SEED = SETS[args.set]
    gen.clean_output_directory = guarded_clean
    patches.update({"generator.SEED": [C.GENERATOR_SEED, PARAM_SEED],
                    "simulator.SEED": [PAPER_EXC_SEED, SETS[args.set]],
                    "clean_output_directory": "guarded: only under EC_comments/data/T5"})
    meta = {"stage": "c_gen_fresh_test", "set": args.set, "bandpass": True,
            "n_structures_total": args.n_total,
            "per_ng_target": gen.compute_ng_targets(args.n_total, gen.NG_CHOICES),
            "param_seed": PARAM_SEED, "excitation_seed": SETS[args.set],
            "paper_param_seed": C.GENERATOR_SEED, "paper_excitation_seed": PAPER_EXC_SEED,
            "n_candidate_modes": gen.N_CANDIDATE_MODES, "patches": patches,
            "git_head": S0.git_head(), "python": sys.executable, "numpy": np.__version__,
            "platform": platform.platform(),
            "threads": {k: os.environ.get(k) for k in ("OMP_NUM_THREADS", "MKL_NUM_THREADS")},
            "started_utc": datetime.now(timezone.utc).isoformat(timespec="seconds")}
    (out_root / "generation_config.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(json.dumps(meta, indent=2), flush=True)

    sys.stdin = io.StringIO("")             # empty, non-TTY: main()'s inspect prompt is skipped
    t0 = time.time()
    gen.main(bandpass=True)
    meta["finished_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    meta["seconds"] = round(time.time() - t0, 1)
    (out_root / "generation_config.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"[done] {args.set}: {meta['seconds']:.0f} s -> {out_root}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
